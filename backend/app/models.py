class Log(Base):
    __tablename__ = "logs"

    __table_args__ = (
        Index("idx_logs_user_deleted_incident", "user_id", "is_deleted", "incident_date"),
    )

    id = Column(Integer, primary_key=True, index=True)
    user_id = Column(Integer, ForeignKey("users.id", ondelete="CASCADE"), nullable=False)
    
    # UUID generated by client for offline-first syncing
    uuid = Column(String, unique=True, index=True, nullable=False)
    title = Column(String, nullable=True)
    
    incident_date = Column(DateTime, nullable=False)
    created_at = Column(DateTime, default=datetime.datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.datetime.utcnow, onupdate=datetime.datetime.utcnow)
    
    # Mood dinosaur foreign key
    mood_dino_id = Column(Integer, ForeignKey("dino_config.id", ondelete="RESTRICT"), nullable=False)
    
    # Description of what happened
    content = Column(Text, nullable=False)
    
    # My thoughts & reflection (now acting as private thoughts / secret words)
    own_thoughts = Column(Text, nullable=True)
    
    is_deleted = Column(Boolean, default=False)
    version = Column(Integer, default=1, nullable=False)
    media_rewarded = Column(Boolean, default=False, nullable=False)


    # Relationships
    user = orm_relationship("User", back_populates="logs")
    dino_config = orm_relationship("DinoConfig")
    attachments = orm_relationship("Attachment", back_populates="log", cascade="all, delete-orphan")
    persons = orm_relationship("Person", secondary=log_person_association, back_populates="logs")

    @property
    def person_uuids(self):
        return [p.uuid for p in self.persons]

