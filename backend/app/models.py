class User(Base):
    __tablename__ = "users"

    id = Column(Integer, primary_key=True, index=True)
    username = Column(String, unique=True, index=True, nullable=False)
    hashed_password = Column(String, nullable=False)
    is_admin = Column(Boolean, default=False)
    nickname = Column(String, nullable=True)

    
    # Camouflage Nine-Palace pattern lock sequence.
    # Default sequence: "1,2,3" represents T-Rex (1) -> Triceratops (2) -> Pterodactyl (3)
    lock_pattern = Column(String, default="1,2,3")
    
    # Flags: "none", "default_requested"
    lock_reset_flag = Column(String, default="none")
    theme = Column(String, default="dark-neon")
    is_active = Column(Boolean, default=True, nullable=False)
    created_at = Column(DateTime, default=datetime.datetime.utcnow)
    
    # Cloud sync assets for sticker gameplay
    sticker_inventory = Column(String, default="", nullable=False)
    canvas_inventory = Column(String, default="3001", nullable=False) # 存储已解锁/购买的画布套 ID，如 "3001,3002"
    egg_energy = Column(Integer, default=100, nullable=False)

    # Relationships
    logs = orm_relationship("Log", back_populates="user", cascade="all, delete-orphan")

